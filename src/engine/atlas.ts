export function atlasAnchor(index: number): [number, number] {
  const anchor = ATLAS_STARS[index % ATLAS_STARS.length];
  const extra = Math.floor(index / ATLAS_STARS.length);
  return [(anchor[1] - 682 + extra * 11) / 670, (anchor[2] - 548 - extra * 9) / 570];
}

export function atlasPosition(world: World, i: number): [number, number] {
  return world.layout === 'atlas'
    ? [world.x[i] * 670 + 630, world.y[i] * 570 + 418]
    : [670 + world.x[i] * 510, 435 + world.y[i] * 390];
}
